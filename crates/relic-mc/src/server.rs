//! Dedicated server installation and launch command construction.

use std::path::{Path, PathBuf};
use std::process::Stdio;
use std::time::Duration;

use relic_proto::{Loader, LoaderKind};
use serde::{Deserialize, Serialize};
use tokio::fs;
use tokio::process::Command;

use crate::http::{Checksum, download, get_json};
use crate::mojang::{self, version_key};
use crate::{Error, Result, java};

/// File in the instance directory describing what is installed there.
pub const MARKER: &str = "relic-launch.json";

const INSTALLER_TIMEOUT: Duration = Duration::from_secs(30 * 60);

/// Mojang's logging configuration that disables JNDI lookups (CVE-2021-44228)
/// for the Log4j builds shipped with 1.12 – 1.16.5. The digest is part of the
/// URL.
const LOG4J_PATCH_FILE: &str = "log4j2_112-116.xml";
const LOG4J_PATCH_SHA1: &str = "02937d122c86ce73319ef9975b58896fc1b491d1";

/// How the server process is started, relative to the instance directory.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(tag = "kind", rename_all = "snake_case")]
pub enum ServerLaunch {
    /// `java -jar <jar> nogui`
    Jar { jar: String },
    /// `java @<dir>/unix_args.txt nogui` (`win_args.txt` on Windows), as
    /// generated by the Forge and NeoForge installers since 1.17.
    ArgsFile { dir: String },
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct Installed {
    pub minecraft_version: String,
    pub loader: Loader,
    /// Java major version Mojang requires for this game version.
    pub java_major: u32,
    pub launch: ServerLaunch,
    /// JVM arguments this installation always needs.
    #[serde(default)]
    pub jvm_args: Vec<String>,
}

pub struct InstallRequest<'a> {
    /// Instance directory; created if missing.
    pub dir: &'a Path,
    /// Directory holding the shared Java runtimes.
    pub runtimes: &'a Path,
    pub minecraft_version: &'a str,
    pub loader: &'a Loader,
}

/// Reads the installation marker of an instance directory.
pub async fn installed(dir: &Path) -> Result<Option<Installed>> {
    match fs::read(dir.join(MARKER)).await {
        Ok(bytes) => Ok(serde_json::from_slice(&bytes).ok()),
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => Ok(None),
        Err(e) => Err(e.into()),
    }
}

/// Installs the server software for `req` into `req.dir`. Does nothing if the
/// directory already holds exactly that game and loader version. World data,
/// mods and configuration in the directory are left alone.
pub async fn install(client: &reqwest::Client, req: &InstallRequest<'_>) -> Result<Installed> {
    let mc = req.minecraft_version;
    if !mojang::is_supported(mc) {
        return Err(Error::Unsupported(format!(
            "Minecraft {mc} is older than {}",
            mojang::MIN_SUPPORTED
        )));
    }
    if let Some(existing) = installed(req.dir).await?
        && existing.minecraft_version == mc
        && existing.loader == *req.loader
    {
        return Ok(existing);
    }
    if req.loader.kind != LoaderKind::Vanilla && req.loader.version.is_empty() {
        return Err(Error::Unsupported("loader version is required".into()));
    }

    let version = mojang::version_json(client, mc).await?;
    let java_major = version.java_major();
    let java = java::ensure_runtime(client, req.runtimes, java_major).await?;
    fs::create_dir_all(req.dir).await?;
    // A marker from a previous installation must not outlive a failed upgrade.
    let _ = fs::remove_file(req.dir.join(MARKER)).await;

    let loader_version = req.loader.version.as_str();
    let launch = match req.loader.kind {
        LoaderKind::Vanilla => {
            let server = version.downloads.server.as_ref().ok_or_else(|| {
                Error::Unsupported(format!("Minecraft {mc} has no dedicated server"))
            })?;
            let jar = "server.jar";
            download(
                client,
                &server.url,
                &req.dir.join(jar),
                &Checksum::Sha1(server.sha1.clone()),
            )
            .await?;
            ServerLaunch::Jar { jar: jar.into() }
        }
        LoaderKind::Fabric => install_fabric(client, req.dir, mc, loader_version).await?,
        LoaderKind::Quilt => install_quilt(client, req.dir, &java, mc, loader_version).await?,
        LoaderKind::Forge => {
            let full = format!("{mc}-{loader_version}");
            let url = format!(
                "https://maven.minecraftforge.net/net/minecraftforge/forge/{full}/forge-{full}-installer.jar"
            );
            run_forge_installer(client, req.dir, &java, &url).await?;
            detect_forge_launch(req.dir, LoaderKind::Forge, mc, loader_version)?
        }
        LoaderKind::NeoForge => {
            let url = format!(
                "https://maven.neoforged.net/releases/net/neoforged/neoforge/{loader_version}/neoforge-{loader_version}-installer.jar"
            );
            run_forge_installer(client, req.dir, &java, &url).await?;
            detect_forge_launch(req.dir, LoaderKind::NeoForge, mc, loader_version)?
        }
    };

    let jvm_args = log4j_mitigation(client, req.dir, mc, req.loader).await?;
    let installed = Installed {
        minecraft_version: mc.to_owned(),
        loader: req.loader.clone(),
        java_major,
        launch,
        jvm_args,
    };
    let json = serde_json::to_vec_pretty(&installed).expect("plain data serializes");
    fs::write(req.dir.join(MARKER), json).await?;
    Ok(installed)
}

#[derive(Deserialize)]
struct FabricInstaller {
    version: String,
    #[serde(default = "yes")]
    stable: bool,
}

fn yes() -> bool {
    true
}

async fn install_fabric(
    client: &reqwest::Client,
    dir: &Path,
    mc: &str,
    loader: &str,
) -> Result<ServerLaunch> {
    let installers: Vec<FabricInstaller> =
        get_json(client, "https://meta.fabricmc.net/v2/versions/installer").await?;
    let installer = installers
        .iter()
        .find(|i| i.stable)
        .or(installers.first())
        .ok_or_else(|| Error::NotFound("Fabric publishes no installer".into()))?;
    // The launcher jar fetches the vanilla server and libraries on first
    // start, verifying them itself. Fabric publishes no digest for this
    // generated jar, so it is always fetched anew.
    let jar = "fabric-server-launch.jar";
    let url = format!(
        "https://meta.fabricmc.net/v2/versions/loader/{mc}/{loader}/{}/server/jar",
        installer.version
    );
    match download(client, &url, &dir.join(jar), &Checksum::None).await {
        Ok(_) => Ok(ServerLaunch::Jar { jar: jar.into() }),
        Err(Error::Status {
            status: 400 | 404, ..
        }) => Err(Error::NotFound(format!(
            "Fabric loader {loader} is not available for Minecraft {mc}"
        ))),
        Err(err) => Err(err),
    }
}

#[derive(Deserialize)]
struct QuiltInstaller {
    url: String,
    hashes: QuiltHashes,
}

#[derive(Deserialize)]
struct QuiltHashes {
    sha256: String,
}

async fn install_quilt(
    client: &reqwest::Client,
    dir: &Path,
    java: &Path,
    mc: &str,
    loader: &str,
) -> Result<ServerLaunch> {
    let installers: Vec<QuiltInstaller> =
        get_json(client, "https://meta.quiltmc.org/v3/versions/installer").await?;
    let installer = installers
        .first()
        .ok_or_else(|| Error::NotFound("Quilt publishes no installer".into()))?;
    let installer_jar = dir.join("relic-installer.jar");
    download(
        client,
        &installer.url,
        &installer_jar,
        &Checksum::Sha256(installer.hashes.sha256.clone()),
    )
    .await?;
    let result = run_installer(
        java,
        dir,
        &[
            "-jar",
            "relic-installer.jar",
            "install",
            "server",
            mc,
            loader,
            "--download-server",
            "--install-dir=.",
        ],
    )
    .await;
    let _ = fs::remove_file(&installer_jar).await;
    result?;

    let jar = "quilt-server-launch.jar";
    if !dir.join(jar).is_file() {
        return Err(Error::Installer(format!(
            "Quilt installer finished without producing {jar}"
        )));
    }
    Ok(ServerLaunch::Jar { jar: jar.into() })
}

async fn run_forge_installer(
    client: &reqwest::Client,
    dir: &Path,
    java: &Path,
    url: &str,
) -> Result<()> {
    // Neither Maven publishes a digest we could pin independently of the
    // download itself; integrity rests on HTTPS to the official repository.
    let installer_jar = dir.join("relic-installer.jar");
    match download(client, url, &installer_jar, &Checksum::None).await {
        Ok(_) => {}
        Err(Error::Status { status: 404, .. }) => {
            return Err(Error::NotFound(format!("no installer at {url}")));
        }
        Err(err) => return Err(err),
    }
    let result = run_installer(
        java,
        dir,
        &["-jar", "relic-installer.jar", "--installServer"],
    )
    .await;
    let _ = fs::remove_file(&installer_jar).await;
    let _ = fs::remove_file(dir.join("relic-installer.jar.log")).await;
    result
}

/// Runs an installer with the instance's own Java, in the instance directory.
async fn run_installer(java: &Path, dir: &Path, args: &[&str]) -> Result<()> {
    tracing::info!(dir = %dir.display(), ?args, "running loader installer");
    let child = Command::new(java)
        .args(args)
        .current_dir(dir)
        .stdin(Stdio::null())
        .stdout(Stdio::piped())
        .stderr(Stdio::piped())
        .kill_on_drop(true)
        .spawn()?;
    let output = tokio::time::timeout(INSTALLER_TIMEOUT, child.wait_with_output())
        .await
        .map_err(|_| Error::Installer("timed out".into()))??;
    if output.status.success() {
        return Ok(());
    }
    let mut text = String::from_utf8_lossy(&output.stdout).into_owned();
    text.push_str(&String::from_utf8_lossy(&output.stderr));
    let tail: Vec<&str> = text.lines().rev().take(15).collect();
    let tail: Vec<&str> = tail.into_iter().rev().collect();
    Err(Error::Installer(format!(
        "{}\n{}",
        output.status,
        tail.join("\n")
    )))
}

/// Works out what the Forge or NeoForge installer left behind. The layout
/// changed several times, so this looks at the files instead of guessing
/// from version numbers.
fn detect_forge_launch(
    dir: &Path,
    kind: LoaderKind,
    mc: &str,
    loader_version: &str,
) -> Result<ServerLaunch> {
    let full = format!("{mc}-{loader_version}");
    let args_dir = match kind {
        LoaderKind::NeoForge => format!("libraries/net/neoforged/neoforge/{loader_version}"),
        _ => format!("libraries/net/minecraftforge/forge/{full}"),
    };
    if dir.join(&args_dir).join("unix_args.txt").is_file()
        || dir.join(&args_dir).join("win_args.txt").is_file()
    {
        return Ok(ServerLaunch::ArgsFile { dir: args_dir });
    }
    for jar in [
        format!("forge-{full}-shim.jar"),
        format!("forge-{full}.jar"),
        format!("forge-{full}-universal.jar"),
    ] {
        if dir.join(&jar).is_file() {
            return Ok(ServerLaunch::Jar { jar });
        }
    }
    Err(Error::Installer(
        "installer finished, but no server launch files were found".into(),
    ))
}

/// JVM arguments closing the Log4Shell hole on game versions that ship a
/// vulnerable Log4j (everything before 1.18.1), following Mojang's advisory.
async fn log4j_mitigation(
    client: &reqwest::Client,
    dir: &Path,
    mc: &str,
    loader: &Loader,
) -> Result<Vec<String>> {
    let key = version_key(mc);
    if key >= version_key("1.18.1") {
        return Ok(Vec::new());
    }
    let forge_like = matches!(loader.kind, LoaderKind::Forge | LoaderKind::NeoForge);
    if key >= version_key("1.17") || forge_like {
        // Forge ships its own logging configuration, which the vanilla file
        // below would replace. The flag is honoured by Log4j 2.10+, which is
        // what Forge for 1.13+ uses.
        if forge_like && key < version_key("1.13") {
            let build = version_key(&loader.version).last().copied().unwrap_or(0);
            if build < 2857 {
                tracing::warn!(
                    version = %loader.version,
                    "this Forge build predates the Log4Shell fix; use 14.23.5.2857 or newer"
                );
            }
        }
        return Ok(vec!["-Dlog4j2.formatMsgNoLookups=true".into()]);
    }
    let url =
        format!("https://launcher.mojang.com/v1/objects/{LOG4J_PATCH_SHA1}/{LOG4J_PATCH_FILE}");
    download(
        client,
        &url,
        &dir.join(LOG4J_PATCH_FILE),
        &Checksum::Sha1(LOG4J_PATCH_SHA1.into()),
    )
    .await?;
    Ok(vec![format!(
        "-Dlog4j.configurationFile={LOG4J_PATCH_FILE}"
    )])
}

/// Records acceptance of the Minecraft EULA. Call only after the admin has
/// explicitly agreed to it; the server refuses to start otherwise.
pub async fn accept_eula(dir: &Path) -> Result<()> {
    fs::write(dir.join("eula.txt"), "eula=true\n").await?;
    Ok(())
}

pub async fn eula_accepted(dir: &Path) -> bool {
    fs::read_to_string(dir.join("eula.txt"))
        .await
        .is_ok_and(|text| {
            text.lines()
                .any(|l| l.trim().eq_ignore_ascii_case("eula=true"))
        })
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct LaunchCommand {
    pub program: PathBuf,
    pub args: Vec<String>,
}

/// Builds the command line for a server. It must be run with the instance
/// directory as working directory.
pub fn launch_command(
    installed: &Installed,
    java: &Path,
    memory_mb: u32,
    extra_jvm_args: &[String],
) -> LaunchCommand {
    let mut args = vec![format!("-Xmx{memory_mb}M")];
    args.extend(installed.jvm_args.iter().cloned());
    args.extend(extra_jvm_args.iter().cloned());
    match &installed.launch {
        ServerLaunch::Jar { jar } => {
            args.push("-jar".into());
            args.push(jar.clone());
        }
        ServerLaunch::ArgsFile { dir } => {
            let file = if cfg!(windows) {
                "win_args.txt"
            } else {
                "unix_args.txt"
            };
            args.push(format!("@{dir}/{file}"));
        }
    }
    args.push("nogui".into());
    LaunchCommand {
        program: java.to_owned(),
        args,
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn touch(path: &Path) {
        std::fs::create_dir_all(path.parent().unwrap()).unwrap();
        std::fs::write(path, b"").unwrap();
    }

    #[test]
    fn forge_launch_is_detected_from_installed_files() {
        let dir = tempfile::tempdir().unwrap();
        let root = dir.path();
        assert!(detect_forge_launch(root, LoaderKind::Forge, "1.12.2", "14.23.5.2860").is_err());

        touch(&root.join("forge-1.12.2-14.23.5.2860.jar"));
        assert_eq!(
            detect_forge_launch(root, LoaderKind::Forge, "1.12.2", "14.23.5.2860").unwrap(),
            ServerLaunch::Jar {
                jar: "forge-1.12.2-14.23.5.2860.jar".into()
            }
        );

        touch(&root.join("libraries/net/minecraftforge/forge/1.20.1-47.4.28/unix_args.txt"));
        assert_eq!(
            detect_forge_launch(root, LoaderKind::Forge, "1.20.1", "47.4.28").unwrap(),
            ServerLaunch::ArgsFile {
                dir: "libraries/net/minecraftforge/forge/1.20.1-47.4.28".into()
            }
        );

        touch(&root.join("libraries/net/neoforged/neoforge/21.1.265/win_args.txt"));
        assert_eq!(
            detect_forge_launch(root, LoaderKind::NeoForge, "1.21.1", "21.1.265").unwrap(),
            ServerLaunch::ArgsFile {
                dir: "libraries/net/neoforged/neoforge/21.1.265".into()
            }
        );
    }

    #[test]
    fn launch_command_orders_jvm_arguments_before_the_target() {
        let mut installed = Installed {
            minecraft_version: "1.16.5".into(),
            loader: Loader {
                kind: LoaderKind::Vanilla,
                version: String::new(),
            },
            java_major: 8,
            launch: ServerLaunch::Jar {
                jar: "server.jar".into(),
            },
            jvm_args: vec!["-Dlog4j.configurationFile=log4j2_112-116.xml".into()],
        };
        let cmd = launch_command(
            &installed,
            Path::new("java"),
            2048,
            &["-javaagent:a.jar=x".into()],
        );
        assert_eq!(
            cmd.args,
            [
                "-Xmx2048M",
                "-Dlog4j.configurationFile=log4j2_112-116.xml",
                "-javaagent:a.jar=x",
                "-jar",
                "server.jar",
                "nogui"
            ]
        );

        installed.jvm_args.clear();
        installed.launch = ServerLaunch::ArgsFile {
            dir: "libraries/net/neoforged/neoforge/21.1.265".into(),
        };
        let cmd = launch_command(&installed, Path::new("java"), 4096, &[]);
        let file = if cfg!(windows) {
            "win_args.txt"
        } else {
            "unix_args.txt"
        };
        assert_eq!(
            cmd.args,
            [
                "-Xmx4096M".to_owned(),
                format!("@libraries/net/neoforged/neoforge/21.1.265/{file}"),
                "nogui".to_owned()
            ]
        );
    }

    #[tokio::test]
    async fn eula_and_marker_round_trip() {
        let dir = tempfile::tempdir().unwrap();
        assert!(!eula_accepted(dir.path()).await);
        assert!(installed(dir.path()).await.unwrap().is_none());
        accept_eula(dir.path()).await.unwrap();
        assert!(eula_accepted(dir.path()).await);
    }
}
